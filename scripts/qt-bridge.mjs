// Bundles the shared drawing and layout code (src/) for the Qt app:
// qt/js/bridge.ts → qt/js/bridge.js (a plain script defining `Inkleaf`).
// Run after changing src/ or qt/js code: npm run qt-bridge
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { readFile } from "node:fs/promises";
import ts from "typescript";

// Qt's script engine has no Unicode property escapes (\p{L}, \p{N}): they're
// spelled out as ranges (Latin, Greek, Cyrillic, Hebrew, Arabic letters; digits).
const LETTERS = "A-Za-z\\u00AA\\u00B5\\u00BA\\u00C0-\\u00D6\\u00D8-\\u00F6\\u00F8-\\u02AF\\u0370-\\u03FF\\u0400-\\u052F\\u05D0-\\u05EA\\u0620-\\u064A\\u066E-\\u06D3\\u06D5\\u06FA-\\u06FF\\u0750-\\u077F\\u08A0-\\u08C9\\u1E00-\\u1FFF\\uFB50-\\uFDFF\\uFE70-\\uFEFC";
const NUMBERS = "0-9\\u0660-\\u0669\\u06F0-\\u06F9\\u00B2\\u00B3\\u00B9\\u00BC-\\u00BE";
function plainRegex(src) {
  let out = "";
  let inClass = false;
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (c === "\\" && src.startsWith("p{", i + 1)) {
      const end = src.indexOf("}", i);
      const name = src.slice(i + 3, end);
      const set = name.startsWith("N") ? NUMBERS : LETTERS;
      out += inClass ? set : "[" + set + "]";
      i = end;
      continue;
    }
    if (c === "\\") {
      out += c + (src[i + 1] ?? "");
      i++;
      continue;
    }
    if (c === "[") inClass = true;
    else if (c === "]") inClass = false;
    out += c;
  }
  return out;
}
function noUnicodeProps(js) {
  // new RegExp("…", "…u…") as TypeScript writes ES5 regex literals
  js = js.replace(/new RegExp\("((?:[^"\\]|\\.)*)", "([a-z]*)"\)/g, (m, body, flags) => {
    if (!flags.includes("u")) return m;
    const src = JSON.parse('"' + body + '"');
    return "new RegExp(" + JSON.stringify(plainRegex(src)) + ", " + JSON.stringify(flags.replace("u", "")) + ")";
  });
  // Regex literals /…\p{…}…/u
  js = js.replace(/\/((?:\\.|\[(?:\\.|[^\]\\])*\]|[^\/\\\[\n])*)\/([a-z]*)/g, (m, body, flags) => {
    if (!flags.includes("u") || !body.includes("\\p{")) return m;
    return "/" + plainRegex(body) + "/" + flags.replace("u", "");
  });
  return js;
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
await build({
  entryPoints: [path.join(root, "qt/js/bridge.ts")],
  outfile: path.join(root, "qt/js/bridge.js"),
  bundle: true,
  format: "iife",
  globalName: "Inkleaf",
  target: "es2016",
  charset: "utf8",
  legalComments: "none",
  banner: { js: "// Generated by scripts/qt-bridge.mjs from the web app's code — don't edit.\nvar globalThis = globalThis || (function () { return this; })();" },
  loader: { ".css": "empty" },
  plugins: [
    {
      // Qt's script engine runs destructuring, for…of and spreads through the
      // iterator protocol, ~50× slower than indexed loops. So every module is
      // first compiled to ES5 by TypeScript (iteration via its __values,
      // __read and __spreadArray helpers), with array fast paths for those
      // helpers (qt/js/polyfills.ts, globalThis.__fast).
      name: "es5-iteration",
      setup(b) {
        b.onLoad({ filter: /\.(ts|js|mjs)$/ }, async (a) => {
          if (a.path.includes("esbuild")) return undefined;
          const src = await readFile(a.path, "utf8");
          const out = ts.transpileModule(src, {
            fileName: a.path,
            compilerOptions: { target: ts.ScriptTarget.ES5, module: ts.ModuleKind.ESNext, downlevelIteration: true, importHelpers: false, isolatedModules: true, allowJs: true, esModuleInterop: true, useDefineForClassFields: false },
          }).outputText;
          const contents = noUnicodeProps(out).replace(/\(this && this\.(__values|__read|__spreadArray)\)/g, "(globalThis.__fast && globalThis.__fast.$1)");
          return { contents, loader: "js" };
        });
      },
    },
  ],
  logLevel: "warning",
});
console.log("qt/js/bridge.js written");

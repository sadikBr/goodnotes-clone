// npm run qt-icons — copies the web app's icons (src/ui.ts) into the Qt app
// (qt/qml/IconData.js), so both use the same artwork.
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("src/ui.ts", "utf8");
const body = src.slice(src.indexOf("export const ICONS = {"), src.indexOf("};", src.indexOf("export const ICONS = {")));
const icons = {};
for (const m of body.matchAll(/^\s+([a-z][\w-]*): svg\(\s*'([^']*)'\s*\),?$/gm)) icons[m[1]] = m[2];
const out = `// Generated by scripts/qt-icons.mjs from src/ui.ts — don't edit.\n.pragma library\nvar paths = ${JSON.stringify(icons, null, 1)};\n`;
writeFileSync("qt/qml/IconData.js", out);
console.log(`${Object.keys(icons).length} icons`);
